SET NAMES utf8mb4;

-- 创建数据库(如不存在)
CREATE DATABASE IF NOT EXISTS travel_planner
    DEFAULT CHARACTER SET utf8mb4
    DEFAULT COLLATE utf8mb4_general_ci;

USE travel_planner;

-- ---------------------------------------------------------------------
-- 1. 景点表:保存景点基础信息,供检索与行程生成使用
-- ---------------------------------------------------------------------
DROP TABLE IF EXISTS t_attraction;
CREATE TABLE t_attraction (
    id          BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '主键',
    name        VARCHAR(128)    NOT NULL COMMENT '景点名称',
    city        VARCHAR(64)     NOT NULL COMMENT '所在城市',
    category    VARCHAR(32)     NOT NULL DEFAULT '其他' COMMENT '类别:自然风光/历史人文/主题乐园/美食街区等',
    rating      DECIMAL(2,1)    NOT NULL DEFAULT 4.5 COMMENT '评分(0-5)',
    price       DECIMAL(10,2)   NOT NULL DEFAULT 0 COMMENT '人均消费(元)',
    description VARCHAR(1024)   NOT NULL DEFAULT '' COMMENT '景点简介',
    tags        VARCHAR(255)    NOT NULL DEFAULT '' COMMENT '标签(逗号分隔)',
    open_time   VARCHAR(64)     NOT NULL DEFAULT '' COMMENT '开放时间',
    address     VARCHAR(255)    NOT NULL DEFAULT '' COMMENT '详细地址',
    create_time DATETIME        NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    update_time DATETIME        NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    PRIMARY KEY (id),
    KEY idx_city (city),
    KEY idx_category (category)
) ENGINE = InnoDB COMMENT = '景点表';

-- ---------------------------------------------------------------------
-- 2. 行程表:保存 Graph 工作流生成的行程规划
-- ---------------------------------------------------------------------
DROP TABLE IF EXISTS t_itinerary;
CREATE TABLE t_itinerary (
    id          BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '主键',
    city        VARCHAR(64)     NOT NULL COMMENT '目标城市',
    days        INT             NOT NULL DEFAULT 3 COMMENT '行程天数',
    budget      DECIMAL(10,2)   NOT NULL DEFAULT 0 COMMENT '预算(元)',
    style       VARCHAR(32)     NOT NULL DEFAULT '常规' COMMENT '出行风格:亲子/情侣/独自/老年/穷游等',
    content     MEDIUMTEXT      NOT NULL COMMENT '行程内容(Markdown)',
    status      TINYINT         NOT NULL DEFAULT 1 COMMENT '状态:1 正常,0 删除',
    create_time DATETIME        NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    update_time DATETIME        NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    PRIMARY KEY (id),
    KEY idx_city (city)
) ENGINE = InnoDB COMMENT = '旅行行程表';

