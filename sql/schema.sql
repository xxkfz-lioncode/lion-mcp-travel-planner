-- 强制本会话按 utf8mb4 解释脚本内的字节。
-- 必要性:Docker 初始化(/docker-entrypoint-initdb.d)或 mysql 客户端在无
-- 语言环境(未设 LANG)时可能把 character_set_client 回退为 latin1,
